#!/usr/bin/env python3
"""Generate tasks-forced.yaml from tasks.yaml so the two cannot drift.

The forced arm starts each prompt with "Use lucid-writer to", which forces the skill to
load (README.md, "Use lucid-writer to…"). The instruction's first letter is lower-cased
to fit the new opening. Nothing else changes, so the paragraph under test is identical.

    python3 bench/prose/make_forced.py           # rewrite tasks-forced.yaml
    python3 bench/prose/make_forced.py --check   # exit 1 if tasks-forced.yaml is stale

Run the forced arm into its own run tree so it never mixes with the unforced runs:
    acumen bench --skill v1 --tasks prose/tasks-forced.yaml --runs prose/runs-forced
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "tasks.yaml"
TARGET = HERE / "tasks-forced.yaml"
PREFIX = "Use lucid-writer to "
BANNER = (
    "# GENERATED by make_forced.py from tasks.yaml. Do not edit: change tasks.yaml and rerun.\n"
    "# Forced-activation arm: each prompt opens with \"Use lucid-writer to\".\n"
    "# Run it into its own tree: acumen bench --skill v1 --tasks prose/tasks-forced.yaml --runs prose/runs-forced\n\n"
)


BLOCK_START = re.compile(r"\s+prompt:\s*[|>][+-]?\s*(#.*)?")
ANY_PROMPT = re.compile(r"\s+prompt:")


def lowered(word_start: str) -> str:
    """Lower-case the first letter to fit "Use lucid-writer to ...", unless the first word is
    an acronym or carries a digit ("PCR", "IL-6", "T2D")."""
    word = word_start.split()[0]
    if any(c.isupper() or c.isdigit() for c in word[1:]):
        return word_start
    return word_start[0].lower() + word_start[1:]


def forced_text(source: str) -> str:
    lines = source.splitlines(keepends=True)
    out, forced, total, i = [], 0, 0, 0
    while i < len(lines):
        out.append(lines[i])
        text = lines[i].rstrip("\n")
        total += bool(ANY_PROMPT.match(text))
        if BLOCK_START.fullmatch(text):
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                out.append(lines[j])
                j += 1
            if j >= len(lines):
                raise SystemExit("a prompt block has no text")
            first = lines[j]
            indent = first[: len(first) - len(first.lstrip())]
            out.append(indent + PREFIX + lowered(first.lstrip()))
            forced += 1
            i = j
        i += 1
    if not total or forced != total:
        raise SystemExit(
            f"tasks.yaml has {total} prompt keys but {forced} were forced; only block "
            "scalars (prompt: | or >) are supported, so rewrite the others"
        )
    return BANNER + "".join(out)


def self_test() -> int:
    head = "tasks:\n  - id: a\n    train:\n      prompt: "
    assert forced_text(head + "|\n\n        PCR results: tighten.\n").splitlines()[-1].endswith("to PCR results: tighten.")
    assert forced_text(head + "|-\n        Tighten this.\n").splitlines()[-1].endswith("to tighten this.")
    assert forced_text(head + ">\n        IL-6 rose.\n").splitlines()[-1].endswith("to IL-6 rose.")
    try:
        forced_text(head + "'inline'\n")
    except SystemExit:
        print("make_forced self-test OK")
        return 0
    raise AssertionError("an inline prompt was not rejected")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    want = forced_text(SOURCE.read_text(encoding="utf-8"))
    if args.check:
        have = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if have != want:
            print("tasks-forced.yaml is out of sync with tasks.yaml: run bench/prose/make_forced.py")
            return 1
        print("tasks-forced.yaml in sync")
        return 0
    TARGET.write_text(want, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
